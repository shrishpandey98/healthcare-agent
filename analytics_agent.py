def _send_email(html_body: str, subject: str) -> bool:
    if DRY_RUN:
        logger.info("[DRY RUN] Would email analytics report to: %s", ANALYTICS_TO_EMAILS)
        return True
    try:
        sg = SendGridAPIClient(SENDGRID_API_KEY)
        mail = Mail(
            from_email=ANALYTICS_FROM_EMAIL,
            to_emails=ANALYTICS_TO_EMAILS,
            subject=subject,
        )
        mail.content = [Content("text/html", html_body)]
        resp = sg.send(mail)
        logger.info("Analytics email sent. Status: %s", resp.status_code)
        return resp.status_code in (200, 202)
    except Exception as e:
        logger.error("Failed to send analytics email: %s", e)
        return False


def run_analytics():
    """Entry point – compute metrics and email report."""
    logger.info("=== Analytics Agent: starting ===")
    records = _get_records()
    metrics = _compute_metrics(records)
    html = _build_html_report(metrics)
    subject = f"Patient Engagement Report – {metrics['report_generated_at'][:10]}"
    ok = _send_email(html, subject)
    if ok:
        logger.info("Analytics report delivered.")
    else:
        logger.error("Analytics report delivery failed.")
    return metrics


if __name__ == "__main__":
    import logging as _log
    _log.basicConfig(level="INFO", format="%(levelname)s %(message)s")
    run_analytics()
