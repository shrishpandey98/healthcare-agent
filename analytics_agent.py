"""
analytics_agent.py – Scheduled Data Analytics Agent.
Reads master Google Sheet, computes KPIs, and emails an HTML report to staff.
Can be run standalone or triggered by schedule in main.py.
"""
import logging
from datetime import datetime
import gspread
from google.oauth2.service_account import Credentials
from sendgrid import SendGridAPIClient
from sendgrid.helpers.mail import Mail, Content
from config import (
    GOOGLE_SHEET_ID, SHEET_NAME, GOOGLE_SERVICE_ACCOUNT_JSON,
    SENDGRID_API_KEY, ANALYTICS_FROM_EMAIL, ANALYTICS_TO_EMAILS,
    DRY_RUN,
)

logger = logging.getLogger(__name__)

SCOPES = [
    "https://www.googleapis.com/auth/spreadsheets.readonly",
    "https://www.googleapis.com/auth/drive.readonly",
]


def _get_records() -> list[dict]:
    creds = Credentials.from_service_account_file(GOOGLE_SERVICE_ACCOUNT_JSON, scopes=SCOPES)
    client = gspread.authorize(creds)
    ws = client.open_by_key(GOOGLE_SHEET_ID).worksheet(SHEET_NAME)
    return ws.get_all_records()


def _compute_metrics(records: list[dict]) -> dict:
    total = len(records)
    sent = sum(1 for r in records if str(r.get("delivery_status", "")).lower() == "sent")
    failed = sum(1 for r in records if str(r.get("delivery_status", "")).lower() == "failed")
    completed = sum(1 for r in records if str(r.get("status", "")).lower() == "completed")
    errors = sum(1 for r in records if str(r.get("status", "")).lower() == "error")

    follow_ups = [r for r in records if str(r.get("action_type", "")).lower() == "follow_up"]
    upsells    = [r for r in records if str(r.get("action_type", "")).lower() == "upsell"]
    feedbacks  = [r for r in records if str(r.get("action_type", "")).lower() == "feedback"]

    upsell_conversions = sum(
        1 for r in upsells if str(r.get("delivery_status", "")).lower() == "sent"
    )

    delivery_rate = round(sent / total * 100, 1) if total else 0

    return {
        "total_records":       total,
        "messages_sent":       sent,
        "messages_failed":     failed,
        "rows_completed":      completed,
        "rows_error":          errors,
        "delivery_rate_pct":   delivery_rate,
        "follow_up_count":     len(follow_ups),
        "upsell_count":        len(upsells),
        "upsell_conversions":  upsell_conversions,
        "feedback_count":      len(feedbacks),
        "follow_up_completion": round(
            sum(1 for r in follow_ups if str(r.get("status","")).lower() == "completed")
            / max(len(follow_ups), 1) * 100, 1
        ),
        "report_generated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }


